"""
03. BPE トークナイザをゼロから実装する
======================================================================
    python 03_bpe_tokenizer.py

外部ライブラリを一切使わず、Byte-Level BPE を最初から作ります。
tokenizers ライブラリ（Hugging Face）が中で何をしているかが完全に分かります。

    STEP 1  なぜ「文字」でも「単語」でもダメなのか
    STEP 2  なぜ「バイト」から始めるのか（未知語がゼロになる理由）
    STEP 3  BPE の訓練を 1 マージずつ観察する
    STEP 4  実際に訓練して語彙を作る
    STEP 5  encode / decode と往復テスト
    STEP 6  語彙サイズを変えると何が変わるか
    STEP 7  特殊トークンと Chat Template

対応ドキュメント: ../02.6-トークナイザを理解する.md
"""

import _corpus
from _bpe import ByteLevelBPE, pretokenize, render   # 実装本体は _bpe.py
from _console import title, sub

# ======================================================================
if __name__ == "__main__":
    # ==================================================================
    title("STEP 1  なぜ「文字」でも「単語」でもダメなのか")
    # ==================================================================
    print("""
【単語単位】 「私 は 猫 が 好き です」
    ○ 直感的
    × 語彙が爆発する（日本語は数十万語）→ Embedding 行列が巨大に
    × 学習時に無かった語が全部「未知語 <unk>」になる
      → 新語・固有名詞・タイポに全滅

【文字単位】 「私 / は / 猫 / が / 好 / き / で / す」
    ○ 語彙が小さい（数千）、未知語なし
    × 系列が長くなる → Attention は O(T^2) なので致命的にコスト増
    × 1 文字が意味を持たない（「猫」はまだしも「き」に意味は無い）

【サブワード（BPE）】 「私 / は / 猫 / が / 好き / です」
    → 頻出語は 1 トークン、珍しい語は分割。両者の良いとこ取り。
      現代の LLM は全部これです。
""")

    # ==================================================================
    title("STEP 2  なぜ「バイト」から始めるのか")
    # ==================================================================
    s = "猫a"
    print(f"  文字列          : {s}")
    print(f"  UTF-8 バイト列  : {list(s.encode('utf-8'))}")
    print("""
  「猫」は UTF-8 で 3 バイト（0xE7 0x8C 0xAB）、'a' は 1 バイト。
  つまり **どんな文字も 0〜255 のバイトに必ず分解できる** ということです。

  ★ だから語彙の出発点に 256 個のバイトを全部入れておけば、
    絵文字だろうが外国語だろうが未知の記号だろうが必ず表現できる。
    これが Byte-Level BPE で <unk> が発生しない理由です。
    （GPT-2 以降のほぼ全ての LLM がこの方式です）
""")

    # ==================================================================
    title("STEP 3  BPE の訓練を 1 マージずつ観察する")
    # ==================================================================
    print("""BPE の訓練は、たった 1 つの操作の繰り返しです:

    「今いちばん頻繁に隣り合っている 2 つのトークンを、1 つに合体させる」

これを目標の語彙数に達するまで続けるだけ。実際に見てみます。
（データは 4 種類の短い行だけ。マージの様子が分かるように verbose 表示します）
""")
    tiny = ("低い低い低い低い低い\n"
            "低くない低くない\n"
            "新しい新しい新しい新しい新しい新しい\n"
            "広い広い広い\n") * 3
    demo = ByteLevelBPE(special_tokens=["<pad>"])
    demo.train(tiny, vocab_size=256 + 1 + 14, verbose=True)
    print("""
  読み方: <0xE3 0x81> のような表示は「UTF-8 として未完成のバイト列」です。
  日本語は 1 文字 3 バイトなので、まず 2 バイトが合体し、次に 3 バイト目が
  合体して初めて 1 文字（'い' など）になります。文字レベルより下から
  積み上がっていく様子が、そのまま見えています。

  → 最終的に「低い」「しい」といった頻出のかたまりが 1 トークンになりました。""")

    # ==================================================================
    title("STEP 4  ミニコーパスで本番の訓練")
    # ==================================================================
    text = _corpus.make_text(n=8000, seed=0)
    print(f"  コーパス: {len(text):,} 文字  ({_corpus.describe()})")

    tok = ByteLevelBPE()
    tok.train(text, vocab_size=400)
    print(f"  語彙サイズ: {len(tok)}")

    sub("学習された「文字として意味のある」トークン")
    learned = []
    for i, v in tok.vocab.items():
        if i < len(tok.special_tokens) or len(v) <= 1:
            continue
        try:
            learned.append((i, v.decode("utf-8")))
        except UnicodeDecodeError:
            pass                       # 途中経過のバイト片は表示しない
    learned.sort(key=lambda x: (-len(x[1]), x[0]))
    for i, s in learned[:20]:
        print(f"    id={i:4d}  '{s}'")
    n_partial = len(tok) - len(learned) - len(tok.special_tokens) - 256
    print(f"\n    ※ このほかに、文字として表示できない中間バイト片が {n_partial} 個。")
    print("      語彙の中身が全部「意味のある単語」になるわけではありません。")

    # ==================================================================
    title("STEP 5  encode / decode と往復テスト")
    # ==================================================================
    for sample in ["猫が魚を食べる。", "太郎は公園へ行く。",
                   "学習していない文章です。ABC 123 🐈"]:
        ids = tok.encode(sample)
        back = tok.decode(ids)
        pieces = [render(tok.vocab[i]).strip("'") for i in ids]
        status = "OK " if back == sample else "NG "
        print(f"\n  [{status}] 入力  : {sample}  （{len(sample)} 文字）")
        print(f"         分割  : {' | '.join(pieces)}")
        print(f"         ID    : {ids}")
        print(f"         復元  : {back}  （{len(ids)} トークン）")
        assert back == sample, "往復に失敗しました"

    print("""
  ★ 学習に無かった文字（絵文字など）もバイトに分解されて必ず復元できます。
    ただし 1 文字が複数トークンになるので「未学習の言語は割高」になります。
    これが「日本語は英語よりトークン消費が多い」と言われる仕組みです。""")

    # ==================================================================
    title("STEP 6  語彙サイズを変えると何が変わるか")
    # ==================================================================
    probe = "猫が魚を食べる。太郎は公園へ行く。" * 5
    print(f"  評価用テキスト: {len(probe)} 文字\n")
    print(f"  {'語彙サイズ':>10} | {'トークン数':>10} | {'圧縮率(文字/トークン)':>22}")
    print("-" * 52)
    for vs in [270, 300, 400, 600, 1000]:
        t2 = ByteLevelBPE().train(text, vocab_size=vs)
        n = len(t2.encode(probe))
        print(f"  {vs:10d} | {n:10d} | {len(probe) / n:22.2f}")

    print("""
  トレードオフ:
    語彙を大きくする → 1 文が短いトークン列になる（＝文脈長を節約できる）
                      → ただし Embedding 行列と出力層が語彙数に比例して巨大化
    語彙を小さくする → 逆

  実例:  LLaMA-2  32,000
         LLaMA-3  128,256
         本教材    6,144（モデルが小さいので語彙も小さくする）

  ★ 目安: Embedding のパラメータ数 = 語彙数 × dim。
    語彙 128k・dim 4096 なら、それだけで 5.2 億パラメータになります。
    小さいモデルで語彙を大きくすると「ほぼ Embedding だけのモデル」になるので、
    モデルサイズと語彙サイズはセットで決めます。""")

    # ==================================================================
    title("STEP 7  特殊トークンと Chat Template")
    # ==================================================================
    print(f"  特殊トークン: {tok.special_tokens}")
    print("""
    <pad>            : バッチ内の長さを揃えるための詰め物（損失からは除外する）
    <s> / </s>       : 文書の開始 / 終了。生成の停止条件にも使う
    <|im_start|> ... : 会話の役割の境界。SFT で必須

  なぜ会話の境界に「特殊トークン」が必要か:
    ただの文字列（例: "User:"）だと、ユーザーが本文に "User:" と書いた瞬間に
    モデルが役割を誤認します（プロンプトインジェクションの温床）。
    語彙表に 1 個だけ存在し、通常のテキストからは絶対に生成されない
    専用 ID を割り当てることで、構造を安全に区切れます。

  Chat Template で整形した実際の文字列:
""")
    messages = [
        {"role": "system", "content": "あなたは親切な助手です。"},
        {"role": "user", "content": "猫は何を食べますか？"},
        {"role": "assistant", "content": "魚を食べます。"},
    ]
    formatted = ""
    for m in messages:
        formatted += f"<|im_start|>{m['role']}\n{m['content']}<|im_end|>\n"
    formatted += "<|im_start|>assistant\n"      # 生成開始の合図
    print("  " + formatted.replace("\n", "\n  "))
    print("""  ★ 最後の "<|im_start|>assistant\\n" が「ここから続きを書け」という指示です。
    これを add_generation_prompt と呼びます。付け忘れると、モデルが
    ユーザーの発言を勝手に続けてしまいます（SFT で最頻出のバグ）。""")

    tok.save("tokenizer_demo.json")
    tok2 = ByteLevelBPE.load("tokenizer_demo.json")
    assert tok2.encode("猫が魚を食べる。") == tok.encode("猫が魚を食べる。")
    print("\n  保存・読み込みテスト: OK (tokenizer_demo.json)")

    title("完了")
    print("""
BPE の全体像:
    訓練 : 最頻の隣接ペアを合体、を語彙数に達するまで繰り返す
    符号化: 学習した順にマージ規則を適用する
    復号  : id -> bytes を連結して UTF-8 デコード

次: python 04_minigpt.py
""")
